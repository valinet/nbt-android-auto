#!/usr/bin/env python3
"""Generate link-only stub sources for the head unit's shared libraries.

The stubs carry only symbol names (and object sizes) so the linker can record a dependency on the real library
(libc.so.3, libm.so.2, libsocket.so.3, libusbdi.so.2). They are never shipped: on the NBT the dynamic loader binds
to the real libraries. Function names come from the headers in ../sysroot plus the imports of binaries built with
the original SDP, so every listed symbol is one the real library provides.
Usage: mkstub.py <include dir> <out dir>
"""
import re, sys
from pathlib import Path

inc, out = Path(sys.argv[1]), Path(sys.argv[2])
out.is_dir() or out.mkdir(parents=True)
DECL = re.compile(r"^[A-Za-z_][\w \*]*?[\s\*]\(?\*?(\w+)\)?\s*\(", re.M)

def names(*headers):
    found = set()
    for h in headers:
        text = open(str(inc / h)).read()
        text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
        for line in re.split(r"[;\n]", text):
            line = line.strip()
            if not line or line.startswith(("#", "typedef", "union", "static", "}", "{", "extern")):
                continue
            if line.startswith("struct") and ("{" in line or "(" not in line):
                continue
            m = DECL.match(line)
            if m:
                found.add(m.group(1))
    return found

LIBM = names("math.h")
SOCKET = names("sys/socket.h", "arpa/inet.h", "netdb.h")
USBDI = names("sys/usbdi.h")
LIBC_HEADERS = ["stdio.h", "stdlib.h", "string.h", "strings.h", "time.h", "sys/time.h", "sys/select.h", "unistd.h",
                "fcntl.h", "sys/stat.h", "signal.h", "sched.h", "pthread.h", "sys/wait.h", "dlfcn.h", "dirent.h",
                "ctype.h", "sys/resource.h", "locale.h", "wchar.h", "wctype.h", "setjmp.h", "sys/mman.h", "errno.h",
                "devctl.h"]
STATIC_ONLY = {"popen", "pclose", "alloca"}          # in libc.a only on QNX 6.5: provided by libqnxopen.a
LIBC = names(*LIBC_HEADERS) - STATIC_ONLY - {"signal"}
LIBC |= {"signal", "_init_libc", "_preinit_array", "_init_array", "_fini_array", "__get_errno_ptr", "stat64",
         "lstat64", "fstat64", "readdir64", "fopen64", "spawn", "pathfind_r", "__cxa_atexit", "__cxa_finalize",
         "fseeko64", "ftello64", "open64", "lseek64"}

def write(name, funcs, objects=(), undefined=()):
    src = ["/* generated by mkstub.py: link-only stub, never shipped */"]
    for f in sorted(funcs):
        src.append("void %s(void) {}" % f)
    for obj, size in objects:
        src.append("char %s[%d] __attribute__((aligned(4)));" % (obj, size))
    for u in undefined:  # make the linker export these from executables (libc refers to them)
        src.append("extern int %s; void *__ref_%s(void) { return &%s; }" % (u, u, u))
    open(str(out / (name + ".c")), "w").write("\n".join(src) + "\n")

write("libc", LIBC, objects=[("_Stdin", 80), ("_Stdout", 80), ("_Stderr", 80), ("environ", 4), ("optarg", 4),
                             ("optind", 4), ("opterr", 4), ("optopt", 4), ("tzname", 8), ("timezone", 4),
                             ("daylight", 4)], undefined=["errno"])
write("libm", LIBM)
write("libsocket", SOCKET)
open(str(out / "libsocket.map"), "w").write("libsocket.so.2 {\n  global:\n" + "".join("    %s;\n" % s for s in sorted(SOCKET)) +
                                   "  local: *;\n};\n")
write("libusbdi", USBDI)
print("libc %d, libm %d, libsocket %d, libusbdi %d symbols" % (len(LIBC), len(LIBM), len(SOCKET), len(USBDI)))
